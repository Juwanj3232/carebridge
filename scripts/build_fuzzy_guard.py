"""
Rebuild backend/fuzzy_guard.txt: real words that spelling tolerance must never "correct" into a one-word red flag.

  python3 scripts/build_fuzzy_guard.py [/usr/share/dict/words]

Example: "cooking" is one letter from "choking", "grasping" from "gasping", "overdone" from "overdose".
Multi-word rules ("chest pain") need their neighbours to match too, so only one-word rules need this guard.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from backend import safety  # noqa: E402

# Common words a dictionary file may lack (inflections, Spanish), checked by hand.
MANUAL = """cooking looking booking hooking grasping overdone smoking choked choker
    painted painting painter matarte matarlo matarla desmayar""".split()


def main() -> None:
    dict_path = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/dict/words")
    words = {w.lower() for w in dict_path.read_text().split() if re.fullmatch(r"[A-Za-z]{4,}", w)}
    words |= set(MANUAL)
    tables = safety.RED_FLAGS + safety.REVIEW_FLAGS
    one_word = {w for w in safety._VOCAB if safety._scan(w, tables)}       # rule words that flag on their own
    guard = sorted(w for w in words if w not in safety._VOCAB and len(w) >= 4
                   and any(c in one_word for c in safety._closest(w)))
    out = ROOT / "backend" / "fuzzy_guard.txt"
    out.write_text("# Generated by scripts/build_fuzzy_guard.py. Real words never corrected into a one-word red flag.\n"
                   + "\n".join(guard) + "\n")
    print(f"{len(guard)} guard words from {len(words)} dictionary words -> {out.relative_to(ROOT)}")
    print("one-word rule words:", " ".join(sorted(one_word)))


if __name__ == "__main__":
    main()
